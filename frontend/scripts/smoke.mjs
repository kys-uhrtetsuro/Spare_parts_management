import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { chromium } from 'playwright'

const cwd = process.cwd().replace(/\/frontend$/, '')
const server = spawn('python', ['backend/manage.py', 'runserver', '127.0.0.1:8000', '--noreload'], {
  cwd, stdio: 'inherit',
})
let browser
try {
  for (let attempt = 0; attempt < 100; attempt++) {
    try {
      const result = await fetch('http://127.0.0.1:8000/api/health')
      if (result.ok) break
    } catch {}
    if (attempt === 99) throw new Error('Django server did not start')
    await new Promise(resolve => setTimeout(resolve, 100))
  }
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, acceptDownloads: true })
  page.on('pageerror', error => { throw error })
  await page.goto('http://127.0.0.1:8000/')
  assert.equal(await page.getByText('ローカル運用').count(), 0)
  await page.getByRole('button', { name: 'システム管理' }).click()
  await page.getByRole('button', { name: '＋ 新規システム名称を登録' }).click()
  await page.getByRole('dialog').getByLabel('システム名').fill('テストシステムA')
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByText('システムを保存しました').waitFor()
  await page.getByRole('dialog', { name: '新規システム登録' }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '機器・部位マスタ' }).click()
  await page.getByRole('button', { name: '＋ 機器を追加' }).click()
  await page.getByRole('dialog').getByLabel('機器名').fill('コンベヤ')
  await page.getByRole('dialog').getByLabel('機器通称（任意）').fill('CV')
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByRole('dialog', { name: '機器マスタ登録' }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '＋ 部位を追加' }).click()
  await page.getByRole('dialog').getByLabel('部位名').fill('駆動部')
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByRole('dialog', { name: '部位を登録' }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '部品分類マスタ' }).click()
  await page.getByRole('button', { name: '＋ 分類を追加' }).click()
  await page.getByRole('dialog').getByLabel('分類名').fill('電装')
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByRole('dialog', { name: '部品分類登録' }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '部品マスタ' }).click()
  await page.getByRole('button', { name: '＋ 部品を追加' }).click()
  await page.getByRole('dialog').getByLabel('品番').fill('P100')
  await page.getByRole('dialog').getByLabel('型式').fill('V1')
  await page.getByRole('dialog').getByLabel('品名').fill('テストセンサ')
  await page.getByRole('dialog').getByLabel('機器（任意）').selectOption({ label: 'コンベヤ（CV）' })
  await page.getByRole('dialog').getByLabel('部位（任意）').selectOption({ label: '駆動部' })
  await page.getByRole('dialog').getByLabel('部品分類（任意）').selectOption({ label: '電装' })
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByText('部品を登録しました').waitFor()
  await page.getByRole('dialog', { name: '新規部品マスタ登録' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('cell', { name: '電装', exact: true }).count(), 1)
  await page.getByRole('button', { name: '現在庫一覧' }).click()
  await page.getByLabel('対象システム').selectOption({ label: 'テストシステムA' })
  await page.getByRole('button', { name: '＋ 入出庫を登録' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('部品を直接入力して検索').fill('P100')
  await dialog.getByText('（完全一致）').waitFor()
  assert.equal(await dialog.getByLabel('企業名').count(), 0)
  await dialog.getByLabel('数量').fill('5')
  await dialog.getByLabel('登録者名').fill('テスト担当者')
  await dialog.getByRole('button', { name: '履歴を登録' }).click()
  await page.getByText('入出庫を記録しました').waitFor()
  await page.getByRole('dialog', { name: '入出庫を登録' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('cell', { name: '5', exact: true }).count(), 1)
  // A new identifier must not rename the old stock row.
  await page.getByRole('button', { name: '部品マスタ' }).click()
  await page.getByRole('button', { name: '編集・後継登録' }).click()
  await page.getByRole('dialog').getByLabel('品番').fill('P200')
  await page.getByRole('dialog').getByRole('button', { name: '保存する' }).click()
  await page.getByRole('dialog', { name: '部品変更・品番/型式引継ぎ' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('cell', { name: 'P100', exact: true }).count(), 1)
  assert.equal(await page.getByRole('cell', { name: 'P200', exact: true }).count(), 1)
  await page.getByRole('button', { name: '現在庫一覧' }).click()
  assert.equal(await page.getByRole('cell', { name: 'P100', exact: true }).count(), 1)
  assert.equal(await page.getByRole('cell', { name: 'P200', exact: true }).count(), 0)
  // Select via the dedicated searchable modal, then register a stock use.
  await page.getByRole('button', { name: '＋ 入出庫を登録' }).click()
  const second = page.getByRole('dialog', { name: '入出庫を登録' })
  await second.getByRole('button', { name: '一覧から選択' }).click()
  const picker = page.getByRole('dialog', { name: '部品一覧から選択' })
  await picker.getByPlaceholder('一覧から部品を検索').fill('P100')
  await picker.getByRole('button', { name: '選択', exact: true }).click()
  await second.getByLabel('区分').selectOption('OUT')
  await second.getByLabel('数量').fill('2')
  await second.getByLabel('登録者名').fill('テスト担当者')
  await second.getByRole('button', { name: '履歴を登録' }).click()
  await page.getByText('入出庫を記録しました').waitFor()
  await page.getByRole('dialog', { name: '入出庫を登録' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('cell', { name: '3', exact: true }).count(), 1)

  await page.getByRole('button', { name: '下限アラート設定' }).click()
  await page.locator('.pick-column').first().locator('.pick-item').first().click()
  await page.locator('.configured input').first().fill('7')
  await page.getByRole('button', { name: '設定を一括保存' }).click()
  await page.getByText('下限アラートを一括保存しました').waitFor()
  await page.getByRole('button', { name: '現在庫一覧' }).click()
  await page.getByText('下限以下').first().waitFor()

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Excel出力' }).click()
  const download = await downloadPromise
  assert.equal(download.suggestedFilename(), 'spare_parts_stock.xlsx')
  console.log('Playwright smoke test OK: master, movement, alert and Excel export')
} finally {
  if (browser) await browser.close()
  server.kill()
}
